DROP FUNCTION IF EXISTS get_user_credit_balance(UUID, UUID);
CREATE OR REPLACE FUNCTION get_user_credit_balance(
  p_user_id UUID,
  p_package_id UUID DEFAULT NULL
)
RETURNS JSONB
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT
    CASE
      WHEN auth.uid() IS NULL OR auth.uid() <> p_user_id THEN
        jsonb_build_object('success', false, 'error', 'unauthorized')
      WHEN p_package_id IS NULL THEN
        COALESCE(
          (
            SELECT jsonb_build_object(
              'success', true,
              'sessions_remaining', COALESCE(SUM(sessions_remaining), 0),
              'active_subscriptions', COUNT(*) FILTER (WHERE expiry_date >= CURRENT_DATE),
              'next_expiry_date', MIN(expiry_date) FILTER (WHERE expiry_date >= CURRENT_DATE)
            )
            FROM user_subscriptions
            WHERE user_id = p_user_id
              AND expiry_date >= CURRENT_DATE
          ),
          jsonb_build_object(
            'success', true,
            'sessions_remaining', 0,
            'active_subscriptions', 0,
            'next_expiry_date', NULL
          )
        )
      ELSE
        COALESCE(
          (
            SELECT jsonb_build_object(
              'success', true,
              'sessions_remaining', COALESCE(SUM(sessions_remaining), 0),
              'active_subscriptions', COUNT(*) FILTER (WHERE expiry_date >= CURRENT_DATE),
              'next_expiry_date', MIN(expiry_date) FILTER (WHERE expiry_date >= CURRENT_DATE)
            )
            FROM user_subscriptions
            WHERE user_id = p_user_id
              AND package_id = p_package_id
              AND expiry_date >= CURRENT_DATE
          ),
          jsonb_build_object(
            'success', true,
            'sessions_remaining', 0,
            'active_subscriptions', 0,
            'next_expiry_date', NULL
          )
        )
    END;
$$;

DROP FUNCTION IF EXISTS create_booking_with_credit(UUID, UUID, UUID);
CREATE OR REPLACE FUNCTION create_booking_with_credit(
  p_user_id UUID,
  p_slot_id UUID,
  p_package_id UUID
)
RETURNS JSONB
LANGUAGE sql
SECURITY DEFINER
AS $$
  WITH auth_check AS (
    SELECT auth.uid() IS NOT NULL AND auth.uid() = p_user_id AS ok
  ),
  subscription AS (
    SELECT us.id, us.package_id, p.allowed_class_names
    FROM user_subscriptions us
    JOIN packages p ON p.id = us.package_id
    WHERE us.user_id = p_user_id
      AND us.package_id = p_package_id
      AND us.expiry_date >= CURRENT_DATE
      AND us.sessions_remaining > 0
    ORDER BY us.expiry_date DESC
    LIMIT 1
    FOR UPDATE
  ),
  slot_state AS (
    SELECT gs.id, gs.gym_id, gs.start_time, gs.total_spots, gs.occupied_spots, gs.class_name
    FROM gym_slots gs
    WHERE gs.id = p_slot_id
      AND gs.start_time > now()
    FOR UPDATE
  ),
  duplicate_booking AS (
    SELECT 1
    FROM bookings b
    WHERE b.user_id = p_user_id
      AND b.slot_id = p_slot_id
      AND b.status = 'upcoming'
    LIMIT 1
  ),
  inserted AS (
    INSERT INTO bookings (
      user_id,
      package_id,
      slot_id,
      status,
      booking_date,
      total_paid,
      session_number,
      qr_code_data
    )
    SELECT
      p_user_id,
      p_package_id,
      p_slot_id,
      'upcoming',
      (SELECT start_time FROM slot_state),
      0,
      1,
      'QR-' || gen_random_uuid()::text
    FROM auth_check a
    WHERE a.ok
      AND EXISTS (SELECT 1 FROM subscription)
      AND EXISTS (SELECT 1 FROM slot_state WHERE occupied_spots < total_spots)
      AND EXISTS (
        SELECT 1
        FROM subscription s
        JOIN slot_state ss ON TRUE
        JOIN package_gyms pg
          ON pg.package_id = s.package_id
         AND pg.gym_id = ss.gym_id
         AND pg.is_active = TRUE
      )
      AND EXISTS (
        SELECT 1
        FROM subscription s
        JOIN slot_state ss ON TRUE
        WHERE COALESCE(array_length(s.allowed_class_names, 1), 0) = 0
           OR ss.class_name = ANY(s.allowed_class_names)
      )
      AND NOT EXISTS (SELECT 1 FROM duplicate_booking)
    RETURNING id
  ),
  decremented_subscription AS (
    UPDATE user_subscriptions us
    SET sessions_remaining = us.sessions_remaining - 1
    WHERE us.id = (SELECT id FROM subscription)
      AND EXISTS (SELECT 1 FROM inserted)
    RETURNING 1
  ),
  incremented_slot AS (
    UPDATE gym_slots gs
    SET occupied_spots = gs.occupied_spots + 1
    WHERE gs.id = p_slot_id
      AND EXISTS (SELECT 1 FROM inserted)
    RETURNING 1
  ),
  updated_booking AS (
    UPDATE bookings b
    SET qr_code_data = jsonb_build_object(
      'booking_id', b.id,
      'user_id', p_user_id,
      'slot_id', p_slot_id,
      'package_id', p_package_id
    )::TEXT
    FROM inserted i
    WHERE b.id = i.id
    RETURNING b.*
  )
  SELECT CASE
    WHEN NOT EXISTS (SELECT 1 FROM auth_check WHERE ok) THEN
      jsonb_build_object('success', false, 'error', 'unauthorized')
    WHEN NOT EXISTS (SELECT 1 FROM subscription) THEN
      jsonb_build_object('success', false, 'error', 'No sessions remaining. Please purchase a package.')
    WHEN NOT EXISTS (SELECT 1 FROM slot_state) THEN
      jsonb_build_object('success', false, 'error', 'Selected slot not found.')
    WHEN EXISTS (SELECT 1 FROM slot_state WHERE occupied_spots >= total_spots) THEN
      jsonb_build_object('success', false, 'error', 'Selected slot is already full.')
    WHEN EXISTS (
      SELECT 1
      FROM subscription s
      JOIN slot_state ss ON TRUE
      WHERE COALESCE(array_length(s.allowed_class_names, 1), 0) > 0
        AND ss.class_name <> ALL(s.allowed_class_names)
    ) THEN
      jsonb_build_object('success', false, 'error', 'This slot is not available for the selected package.')
    WHEN NOT EXISTS (
      SELECT 1
      FROM subscription s
      JOIN slot_state ss ON TRUE
      JOIN package_gyms pg
        ON pg.package_id = s.package_id
       AND pg.gym_id = ss.gym_id
       AND pg.is_active = TRUE
    ) THEN
      jsonb_build_object('success', false, 'error', 'This package is not available for the selected gym.')
    WHEN EXISTS (SELECT 1 FROM duplicate_booking) THEN
      jsonb_build_object('success', false, 'error', 'You already booked this slot.')
    WHEN NOT EXISTS (SELECT 1 FROM inserted) THEN
      jsonb_build_object('success', false, 'error', 'Unable to create booking.')
    ELSE
      jsonb_build_object('success', true, 'booking', (SELECT to_jsonb(ub) FROM updated_booking ub LIMIT 1))
  END;
$$;

DROP FUNCTION IF EXISTS cancel_booking_with_refund(UUID, UUID);
CREATE OR REPLACE FUNCTION cancel_booking_with_refund(
  p_booking_id UUID,
  p_user_id UUID
)
RETURNS JSONB
LANGUAGE sql
SECURITY DEFINER
AS $$
  WITH auth_check AS (
    SELECT auth.uid() IS NOT NULL AND auth.uid() = p_user_id AS ok
  ),
  booking_row AS (
    SELECT b.id, b.package_id, b.slot_id, b.status
    FROM bookings b
    WHERE b.id = p_booking_id
      AND b.user_id = p_user_id
    FOR UPDATE
  ),
  updated_booking AS (
    UPDATE bookings b
    SET status = 'missed'
    WHERE b.id = p_booking_id
      AND EXISTS (SELECT 1 FROM auth_check WHERE ok)
      AND EXISTS (SELECT 1 FROM booking_row WHERE status = 'upcoming')
    RETURNING 1
  ),
  updated_subscription AS (
    UPDATE user_subscriptions us
    SET sessions_remaining = us.sessions_remaining + 1
    WHERE us.id = (
      SELECT us2.id
      FROM user_subscriptions us2
      WHERE us2.user_id = p_user_id
        AND us2.package_id = (SELECT br.package_id FROM booking_row br LIMIT 1)
      ORDER BY us2.expiry_date DESC
      LIMIT 1
    )
      AND EXISTS (SELECT 1 FROM updated_booking)
    RETURNING 1
  ),
  updated_slot AS (
    UPDATE gym_slots gs
    SET occupied_spots = GREATEST(gs.occupied_spots - 1, 0)
    WHERE gs.id = (SELECT br.slot_id FROM booking_row br LIMIT 1)
      AND (SELECT br.slot_id FROM booking_row br LIMIT 1) IS NOT NULL
      AND EXISTS (SELECT 1 FROM updated_booking)
    RETURNING 1
  )
  SELECT CASE
    WHEN NOT EXISTS (SELECT 1 FROM auth_check WHERE ok) THEN
      jsonb_build_object('success', false, 'error', 'unauthorized')
    WHEN NOT EXISTS (SELECT 1 FROM booking_row) THEN
      jsonb_build_object('success', false, 'error', 'Booking not found.')
    WHEN EXISTS (SELECT 1 FROM booking_row WHERE status <> 'upcoming') THEN
      jsonb_build_object('success', false, 'error', 'Only upcoming bookings can be cancelled.')
    WHEN NOT EXISTS (SELECT 1 FROM updated_booking) THEN
      jsonb_build_object('success', false, 'error', 'Unable to cancel booking.')
    ELSE
      jsonb_build_object('success', true)
  END;
$$;

DROP FUNCTION IF EXISTS reschedule_booking(UUID, UUID, UUID);
CREATE OR REPLACE FUNCTION reschedule_booking(
  p_booking_id UUID,
  p_user_id UUID,
  p_new_slot_id UUID
)
RETURNS JSONB
LANGUAGE sql
SECURITY DEFINER
AS $$
  WITH auth_check AS (
    SELECT auth.uid() IS NOT NULL AND auth.uid() = p_user_id AS ok
  ),
  booking_row AS (
    SELECT b.id, b.package_id, b.slot_id, b.status
    FROM bookings b
    WHERE b.id = p_booking_id
      AND b.user_id = p_user_id
    FOR UPDATE
  ),
  new_slot AS (
    SELECT gs.id, gs.gym_id, gs.total_spots, gs.occupied_spots, gs.class_name
    FROM gym_slots gs
    WHERE gs.id = p_new_slot_id
    FOR UPDATE
  ),
  updated_booking AS (
    UPDATE bookings b
    SET slot_id = p_new_slot_id
    WHERE b.id = p_booking_id
      AND EXISTS (SELECT 1 FROM auth_check WHERE ok)
      AND EXISTS (SELECT 1 FROM booking_row WHERE status = 'upcoming')
      AND EXISTS (SELECT 1 FROM new_slot WHERE occupied_spots < total_spots)
      AND EXISTS (
        SELECT 1
        FROM booking_row br
        JOIN packages p ON p.id = br.package_id
        JOIN new_slot ns ON TRUE
        JOIN package_gyms pg
          ON pg.package_id = br.package_id
         AND pg.gym_id = ns.gym_id
         AND pg.is_active = TRUE
        WHERE COALESCE(array_length(p.allowed_class_names, 1), 0) = 0
           OR ns.class_name = ANY(p.allowed_class_names)
      )
      AND EXISTS (SELECT 1 FROM booking_row WHERE slot_id IS DISTINCT FROM p_new_slot_id)
    RETURNING 1
  ),
  old_slot_update AS (
    UPDATE gym_slots gs
    SET occupied_spots = GREATEST(gs.occupied_spots - 1, 0)
    WHERE gs.id = (SELECT br.slot_id FROM booking_row br LIMIT 1)
      AND EXISTS (SELECT 1 FROM updated_booking)
      AND (SELECT br.slot_id FROM booking_row br LIMIT 1) IS NOT NULL
    RETURNING 1
  ),
  new_slot_update AS (
    UPDATE gym_slots gs
    SET occupied_spots = gs.occupied_spots + 1
    WHERE gs.id = p_new_slot_id
      AND EXISTS (SELECT 1 FROM updated_booking)
    RETURNING 1
  )
  SELECT CASE
    WHEN NOT EXISTS (SELECT 1 FROM auth_check WHERE ok) THEN
      jsonb_build_object('success', false, 'error', 'unauthorized')
    WHEN NOT EXISTS (SELECT 1 FROM booking_row) THEN
      jsonb_build_object('success', false, 'error', 'Booking not found.')
    WHEN EXISTS (SELECT 1 FROM booking_row WHERE status <> 'upcoming') THEN
      jsonb_build_object('success', false, 'error', 'Only upcoming bookings can be rescheduled.')
    WHEN EXISTS (SELECT 1 FROM booking_row WHERE slot_id = p_new_slot_id) THEN
      jsonb_build_object('success', false, 'error', 'Please choose a different slot.')
    WHEN NOT EXISTS (SELECT 1 FROM new_slot) THEN
      jsonb_build_object('success', false, 'error', 'New slot not found.')
    WHEN EXISTS (SELECT 1 FROM new_slot WHERE occupied_spots >= total_spots) THEN
      jsonb_build_object('success', false, 'error', 'New slot is already full.')
    WHEN NOT EXISTS (
      SELECT 1
      FROM booking_row br
      JOIN package_gyms pg ON pg.package_id = br.package_id AND pg.is_active = TRUE
      JOIN new_slot ns ON ns.gym_id = pg.gym_id
    ) THEN
      jsonb_build_object('success', false, 'error', 'This package is not available for the selected gym.')
    WHEN NOT EXISTS (SELECT 1 FROM updated_booking) THEN
      jsonb_build_object('success', false, 'error', 'Unable to reschedule booking.')
    ELSE
      jsonb_build_object('success', true)
  END;
$$;

