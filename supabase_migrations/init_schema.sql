CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Core identity tables
CREATE TABLE IF NOT EXISTS profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT UNIQUE NOT NULL,
  name TEXT,
  bio TEXT,
  profile_picture_url TEXT,
  gender TEXT,
  birthdate DATE,
  age INT,
  current_weight DOUBLE PRECISION,
  initial_weight DOUBLE PRECISION,
  weight_goal DOUBLE PRECISION,
  height DOUBLE PRECISION,
  step_goal INT,
  hydration_goal INTEGER,
  profile_completed BOOLEAN DEFAULT false,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weight_history (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  weight DOUBLE PRECISION NOT NULL,
  recorded_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Booking tables
CREATE TABLE IF NOT EXISTS packages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  description TEXT,
  price NUMERIC NOT NULL,
  sessions_count INTEGER NOT NULL,
  category TEXT NOT NULL DEFAULT 'Gym',
  badge TEXT,
  is_featured BOOLEAN NOT NULL DEFAULT FALSE,
  icon_name TEXT NOT NULL DEFAULT 'fitness_center',
  stripe_price_id TEXT,
  validity_days INTEGER NOT NULL DEFAULT 30,
  allowed_class_names TEXT[] NOT NULL DEFAULT '{}',
  benefits TEXT[] NOT NULL DEFAULT '{}',
  rules TEXT[] NOT NULL DEFAULT '{}',
  gym_names TEXT[] NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS gyms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  venue TEXT,
  address TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT gyms_status_check CHECK (status = ANY (ARRAY['active', 'inactive']))
);

CREATE TABLE IF NOT EXISTS package_gyms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  package_id UUID NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  gym_id UUID NOT NULL REFERENCES gyms(id) ON DELETE CASCADE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT package_gyms_unique_package_gym UNIQUE (package_id, gym_id)
);

CREATE TABLE IF NOT EXISTS gym_slots (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  gym_id UUID NOT NULL REFERENCES gyms(id) ON DELETE CASCADE,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  class_name TEXT NOT NULL,
  coach_name TEXT,
  location TEXT,
  total_spots INTEGER NOT NULL DEFAULT 20,
  occupied_spots INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT gym_slots_time_check CHECK (end_time > start_time),
  CONSTRAINT gym_slots_capacity_check CHECK (occupied_spots >= 0 AND occupied_spots <= total_spots)
);

CREATE TABLE IF NOT EXISTS bookings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  package_id UUID REFERENCES packages(id),
  slot_id UUID REFERENCES gym_slots(id),
  booking_date TIMESTAMPTZ NOT NULL DEFAULT now(),
  status TEXT NOT NULL DEFAULT 'upcoming',
  total_paid NUMERIC,
  receipt_url TEXT,
  qr_code_data TEXT,
  session_number INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT bookings_status_check CHECK (
    status = ANY (
      ARRAY[
        'upcoming'::TEXT,
        'missed'::TEXT,
        'completed'::TEXT
      ]
    )
  )
);

CREATE TABLE IF NOT EXISTS user_subscriptions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  package_id UUID NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  sessions_remaining INTEGER NOT NULL DEFAULT 0,
  expiry_date DATE NOT NULL,
  last_payment_intent_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT user_subscriptions_sessions_non_negative CHECK (sessions_remaining >= 0),
  CONSTRAINT user_subscriptions_unique_user_package UNIQUE (user_id, package_id)
);

CREATE TABLE IF NOT EXISTS stripe_webhook_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stripe_event_id TEXT NOT NULL UNIQUE,
  event_type TEXT NOT NULL,
  payload JSONB NOT NULL,
